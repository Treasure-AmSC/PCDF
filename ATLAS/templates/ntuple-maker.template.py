"""Convert an ATLAS {{INPUT_FORMAT}} DAOD to Parquet folders.

Generated by the PCDF ATLAS ntuple wizard.
{{INPUT_NOTE}}
"""

import re
import shutil
from pathlib import Path

import awkward as ak
import click
import numba as nb
import numpy as np
import uproot as up
from rich import print
from rich.traceback import install as install_rich_traceback

POINT = "[green][b]‣[/b][/green]"
INPUT_FORMAT = "{{INPUT_FORMAT}}"
OBJECTS = {{OBJECTS}}
MESSAGES = {{MESSAGES:converter}}


def message(key, **values):
    """Return a user-facing message, filling in each double-brace placeholder from values."""
    return re.sub(r"{{([A-Z0-9_]+)}}", lambda match: str(values.get(match.group(1), match.group(0))), MESSAGES[key])

JET_LINK_ALIASES = {
    "constLinks": "AnalysisJetsAuxDyn.constituentLinks",
    "trackLinks": "AnalysisJetsAuxDyn.GhostTrack",
}


def selected_aliases(name):
    return dict(OBJECTS[name]["aliases"])


def make_idx(arr):
    ndim = arr.ndim
    counts = []
    for i in range(0, ndim):
        try:
            sizes = ak.num(arr, axis=-1 - i)
            counts.append(ak.flatten(sizes, axis=None))
        except Exception:
            # The outermost dimension is never read.
            pass
    idx = ak.local_index(ak.flatten(arr, axis=None))
    for _ in range(1, ndim):
        idx = ak.unflatten(idx, counts.pop(0))
    return idx


def rec_flatten(arr):
    flat = arr
    for _ in range(1, arr.ndim):
        flat = ak.flatten(flat, axis=-1)
    return flat


def first_field(record):
    fields = ak.fields(record)
    if not fields:
        raise ValueError(message("converter.no-variables"))
    return record[fields[0]]


def select_per_jet(base, indexer):
    @nb.jit
    def process(
        builder: ak.ArrayBuilder,
        values: ak.Array,
        links: ak.Array,
    ):
        for values_evt, links_evt in zip(values, links):
            builder.begin_list()
            for links_jet in links_evt:
                builder.begin_list()
                for link in links_jet:
                    builder.append(values_evt[link])
                builder.end_list()
            builder.end_list()
        return builder

    selected = {}
    for name, values in ak.unzip(base, how=dict).items():
        builder = ak.ArrayBuilder()
        result = process(builder, values, indexer)
        selected[name] = result.snapshot()
    return ak.zip(selected)


def identify_constituent_hashes(keys, charged_sizes, neutral_sizes):
    """Return the container hashes of the charged and neutral constituents.

    Each container is linked once per element, so a hash's link count in an
    event equals its container's size there. An event can only tell the two
    containers apart when their sizes differ, so use the first such event.
    """
    differing = np.flatnonzero(
        ak.to_numpy(charged_sizes) != ak.to_numpy(neutral_sizes)
    )
    for event in differing[:100]:
        hashes, counts = np.unique(
            ak.flatten(keys[event], axis=None), return_counts=True
        )
        if len(hashes) != 2:
            continue
        sizes = (int(charged_sizes[event]), int(neutral_sizes[event]))
        if tuple(int(count) for count in counts) == sizes:
            return hashes[0], hashes[1]
        if tuple(int(count) for count in counts) == sizes[::-1]:
            return hashes[1], hashes[0]
    raise click.ClickException(message("converter.hashes-ambiguous"))


def check_links_in_range(links, sizes, label):
    """Fail clearly if a link points past the end of its container."""
    largest = ak.fill_none(ak.max(ak.flatten(links, axis=-1), axis=-1), -1)
    bad = np.flatnonzero(ak.to_numpy(largest) >= ak.to_numpy(sizes))
    if len(bad):
        raise click.ClickException(
            message("converter.links-out-of-range", COUNT=len(bad), LABEL=label, FIRST=bad[0])
        )


def split_constituent_aliases():
    charged = {}
    neutral = {}
    for name, branches in selected_aliases("Const").items():
        charged[name] = branches[0]
        neutral[name] = branches[1]
    return charged, neutral


INDEX_FILE_BITS = 16
INDEX_LOCAL_BITS = 64 - INDEX_FILE_BITS
MAX_FILE_NUMBER = (1 << INDEX_FILE_BITS) - 1
MAX_LOCAL_INDEX = (1 << INDEX_LOCAL_BITS) - 1
UINT64_MODULUS = 1 << 64
INT64_SIGN_BIT = 1 << 63


def as_signed_int64(value):
    return value if value < INT64_SIGN_BIT else value - UINT64_MODULUS


def partition_from_input(input_path, root_uuid):
    pattern = re.compile(
        r"(?:^|\.)DAOD_[^.]+\.(?P<tid>\d+)\._(?P<file_number>\d+)"
        r"\.pool\.root(?:\.\d+)?$"
    )
    match = pattern.search(input_path.name)
    if match:
        file_number = int(match.group("file_number"))
        if file_number > MAX_FILE_NUMBER:
            raise click.ClickException(
                message("converter.file-number-too-large", NUMBER=file_number, MAXIMUM=MAX_FILE_NUMBER)
            )
        return {
            "parts": (
                f"tid={match.group('tid')}",
                f"fileNumber={file_number}",
            ),
            "indexPrefix": file_number,
        }

    # A filename without embedded ATLAS identifiers provides no genuine task ID
    # or file number. Use the file's ROOT UUID instead of inventing values for
    # those ATLAS-specific fields.
    uuid_value = getattr(root_uuid, "int", None)
    if not isinstance(uuid_value, int) or not 0 <= uuid_value < (1 << 128):
        raise click.ClickException(message("converter.no-partition-identity", PATH=input_path))
    uuid_high = as_signed_int64(uuid_value >> 64)
    uuid_low = as_signed_int64(uuid_value & (UINT64_MODULUS - 1))
    partition = {
        "parts": (
            f"fileUUIDHigh={uuid_high}",
            f"fileUUIDLow={uuid_low}",
        ),
        "indexPrefix": 0,
    }
    click.echo(
        message("converter.uuid-partitions", HIGH=uuid_high, LOW=uuid_low, PATH=input_path),
        err=True,
    )
    return partition


def encode_global_index(local_index, file_number, label):
    flattened = ak.flatten(local_index, axis=None)
    if len(flattened) > 0 and int(ak.max(flattened)) > MAX_LOCAL_INDEX:
        raise click.ClickException(
            message("converter.local-index-too-large", LABEL=label, MAXIMUM=MAX_LOCAL_INDEX)
        )
    prefix = np.uint64(file_number << INDEX_LOCAL_BITS)
    return ak.values_astype(local_index, np.uint64) + prefix


def make_global_idx(arr, file_number, label):
    return encode_global_index(make_idx(arr), file_number, label)



def selected_output_partition_paths(output, partition):
    return [
        (output / config["folder"]).joinpath(*partition["parts"])
        for config in OBJECTS.values()
    ]


def existing_output_partitions(output, partition):
    if not output.exists():
        return []
    return [path for path in selected_output_partition_paths(output, partition) if path.exists()]


def all_selected_output_partitions_exist(output, partition):
    paths = selected_output_partition_paths(output, partition)
    return bool(paths) and all(path.exists() for path in paths)


def cleanup_output_partitions(output, partition):
    if not output.exists():
        return
    for target in selected_output_partition_paths(output, partition):
        if target.exists():
            shutil.rmtree(target)
        parent = target.parent
        for _ in range(len(partition["parts"]) - 1):
            try:
                parent.rmdir()
            except OSError:
                break
            parent = parent.parent

def write_object(output, folder, partition, payload, flatten=True):
    path = (output / folder).joinpath(*partition["parts"])
    if path.exists():
        raise click.ClickException(message("converter.partition-exists", PATH=path))
    path.mkdir(parents=True)
    data = rec_flatten(payload) if flatten else payload
    ak.to_parquet(data, path / "data.parquet")


@click.command()
@click.argument(
    "input",
    type=click.Path(
        exists=True,
        dir_okay=False,
        resolve_path=True,
        path_type=Path,
    ),
    required=True,
)
@click.option(
    "-o",
    "--output",
    type=click.Path(
        exists=False,
        dir_okay=True,
        file_okay=False,
        path_type=Path,
    ),
    required=True,
)
@click.option(
    "--skip-unreadable/--fail-unreadable",
    default=True,
    show_default=True,
    help=MESSAGES["converter.help-skip-unreadable"],
)
@click.option(
    "--skip-existing/--fail-existing",
    default=True,
    show_default=True,
    help=MESSAGES["converter.help-skip-existing"],
)
def ntuple_maker(input, output, skip_unreadable, skip_existing):
    try:
        with up.open(input, handler=up.source.file.MemmapSource) as file:
            partition = partition_from_input(input, file.file.uuid)
            existing_partitions = existing_output_partitions(output, partition)
            if existing_partitions:
                paths = ", ".join(str(path) for path in existing_partitions[:3])
                suffix = "" if len(existing_partitions) <= 3 else message("converter.partitions-more", COUNT=len(existing_partitions) - 3)
                detail = message("converter.partition-exists-for", INPUT=input, PATHS=paths, SUFFIX=suffix)
                if skip_existing and all_selected_output_partitions_exist(output, partition):
                    click.echo(message("converter.skipping-complete", DETAIL=detail), err=True)
                    return
                raise click.ClickException(message("converter.incomplete-partitions", DETAIL=detail))

            tree = file["CollectionTree"]
            aliases = {
                name: selected_aliases(name)
                for name in OBJECTS
            }

            if "Const" in OBJECTS:
                const_aliases = split_constituent_aliases()
                aliases.pop("Const", None)
                aliases["c_const"] = const_aliases[0]
                aliases["n_const"] = const_aliases[1]
                aliases["Jet"] = {
                    **aliases.get("Jet", {}),
                    "__jetIndexSource": "AnalysisJetsAuxDyn.pt",
                    "constLinks": JET_LINK_ALIASES["constLinks"],
                }
            if "Track" in OBJECTS:
                aliases["Jet"] = {
                    **aliases.get("Jet", {}),
                    "__jetIndexSource": "AnalysisJetsAuxDyn.pt",
                    "trackLinks": JET_LINK_ALIASES["trackLinks"],
                }

            arrays = {
                name: tree.arrays(
                    expressions=object_aliases.keys(),
                    aliases=object_aliases,
                )
                for name, object_aliases in aliases.items()
                if object_aliases
            }
    except up.exceptions.KeyInFileError as error:
        raise click.ClickException(message("converter.missing-branch", INPUT=input, ERROR=error)) from error
    except OSError as error:
        if skip_unreadable:
            click.echo(message("converter.skipping-unreadable", INPUT=input, ERROR=error), err=True)
            return
        raise click.ClickException(message("converter.cannot-read", INPUT=input, ERROR=error)) from error

    event = arrays["Event"]
    if len(event) == 0:
        raise click.ClickException(message("converter.no-events", INPUT=input))

    print(f"{POINT} {message('converter.read-events', COUNT=len(event))}")
    event_index = make_global_idx(
        first_field(event),
        partition["indexPrefix"],
        "eventIndex",
    )
    output.mkdir(parents=True, exist_ok=True)

    if "Event" in OBJECTS:
        print(f"  {POINT} {message('converter.step-events')}")
        event_payload = {"eventIndex": event_index}
        event_payload.update(ak.unzip(event, how=dict))
        write_object(
            output,
            OBJECTS["Event"]["folder"],
            partition,
            ak.zip(event_payload),
        )

    jet_index = None
    jet = arrays.get("Jet")
    if jet is not None:
        jet_index_source = (
            jet["__jetIndexSource"]
            if "__jetIndexSource" in ak.fields(jet)
            else first_field(jet)
        )
        jet_index = make_global_idx(
            jet_index_source,
            partition["indexPrefix"],
            "jetIndex",
        )
        if "Jet" in OBJECTS:
            print(f"  {POINT} {message('converter.step-jets')}")
            jet_payload = {
                "jetIndex": jet_index,
                "eventIndex": event_index,
            }
            jet_payload.update(
                {
                    name: jet[name]
                    for name in selected_aliases("Jet")
                }
            )
            write_object(
                output,
                OBJECTS["Jet"]["folder"],
                partition,
                ak.zip(jet_payload),
            )

    if "Const" in OBJECTS:
        print(f"  {POINT} {message('converter.step-reading-constituents')}")
        charged_sizes = ak.num(arrays["c_const"][ak.fields(arrays["c_const"])[0]])
        neutral_sizes = ak.num(arrays["n_const"][ak.fields(arrays["n_const"])[0]])
        charged_hash, neutral_hash = identify_constituent_hashes(
            jet.constLinks.m_persKey, charged_sizes, neutral_sizes
        )
        charged_links = jet.constLinks.m_persIndex[
            jet.constLinks.m_persKey == charged_hash
        ]
        neutral_links = jet.constLinks.m_persIndex[
            jet.constLinks.m_persKey == neutral_hash
        ]
        check_links_in_range(charged_links, charged_sizes, message("converter.label-charged"))
        check_links_in_range(neutral_links, neutral_sizes, message("converter.label-neutral"))
        charged = select_per_jet(arrays["c_const"], charged_links)
        neutral = select_per_jet(arrays["n_const"], neutral_links)
        constituents = ak.concatenate(
            [charged, neutral],
            axis=2,
        )
        const_index = make_global_idx(
            first_field(constituents),
            partition["indexPrefix"],
            "constIndex",
        )
        const_payload = {
            "constIndex": const_index,
            "jetIndex": jet_index,
            "eventIndex": event_index,
        }
        const_fields = ak.unzip(constituents, how=dict)
        const_payload.update(const_fields)
        print(f"  {POINT} {message('converter.step-constituents')}")
        write_object(
            output,
            OBJECTS["Const"]["folder"],
            partition,
            ak.zip(const_payload),
        )

    if "Track" in OBJECTS:
        print(f"  {POINT} {message('converter.step-reading-tracks')}")
        tracks = select_per_jet(
            arrays["Track"],
            jet.trackLinks.m_persIndex[
                jet.trackLinks.m_persKey != 0
            ],
        )
        track_index = make_global_idx(
            first_field(tracks),
            partition["indexPrefix"],
            "trackIndex",
        )
        track_payload = {
            "trackIndex": track_index,
            "jetIndex": jet_index,
            "eventIndex": event_index,
        }
        track_payload.update(ak.unzip(tracks, how=dict))
        print(f"  {POINT} {message('converter.step-tracks')}")
        write_object(
            output,
            OBJECTS["Track"]["folder"],
            partition,
            ak.zip(track_payload),
        )

    simple_objects = (
        "LargeRJet",
        "Electron",
        "Muon",
        "Photon",
    )
    for name in simple_objects:
        if name not in OBJECTS:
            continue
        record = arrays[name]
        object_index = make_global_idx(
            first_field(record),
            partition["indexPrefix"],
            OBJECTS[name]["index_name"],
        )
        payload = {
            OBJECTS[name]["index_name"]: object_index,
            "eventIndex": event_index,
        }
        payload.update(ak.unzip(record, how=dict))
        print(f"  {POINT} {OBJECTS[name]['folder']}")
        write_object(
            output,
            OBJECTS[name]["folder"],
            partition,
            ak.zip(payload),
        )

    if "MET" in OBJECTS:
        print(f"  {POINT} {message('converter.step-met')}")
        met_payload = {"eventIndex": event_index}
        met_fields = ak.unzip(arrays["MET"], how=dict)
        met_payload.update(met_fields)
        write_object(
            output,
            OBJECTS["MET"]["folder"],
            partition,
            ak.zip(met_payload),
            flatten=False,
        )

    print(f"{POINT} {message('converter.complete')}")


if __name__ == "__main__":
    install_rich_traceback()
    ntuple_maker()
